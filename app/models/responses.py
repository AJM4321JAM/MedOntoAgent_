from typing import Literal

from pydantic import BaseModel, Field

from app.models.constraints import (
    ConstraintType,
)


class CitationReference(BaseModel):
    """
    Reference to one retrieved evidence chunk used
    in an answer.
    """

    chunk_id: str = Field(
        min_length=1,
    )


class BaselineLLMOutput(BaseModel):
    """
    Structured output required directly from the baseline LLM.
    """

    answer: str = Field(
        min_length=1,
    )

    citations: list[
        CitationReference
    ]

    status: Literal[
        "ANSWERED",
        "ABSTAINED",
    ]


class BaselineQueryResponse(BaseModel):
    """
    Public API response returned by the conventional
    baseline RAG system.
    """

    query: str = Field(
        min_length=1,
    )

    answer: str = Field(
        min_length=1,
    )

    citations: list[
        CitationReference
    ]

    retrieved_chunk_ids: list[str]

    status: Literal[
        "ANSWERED",
        "ABSTAINED",
    ]


class MedOntoClaim(BaseModel):
    """
    One factual claim in a MedOntoAgent draft together
    with the retrieved chunks claimed to support it.
    """

    claim_text: str = Field(
        min_length=1,
    )

    citation_chunk_ids: list[str] = Field(
        min_length=1,
    )


class MedOntoConstraintReference(BaseModel):
    """
    One ontology constraint reported back by generation.

    Python later verifies that this exactly corresponds to
    an application-supplied ontology constraint.
    """

    constraint_type: ConstraintType

    subject_name: str = Field(
        min_length=1,
    )

    predicate_name: str = Field(
        min_length=1,
    )

    object_name: str = Field(
        min_length=1,
    )


class MedOntoDraftOutput(BaseModel):
    """
    Structured candidate answer produced by MedOntoAgent.

    DRAFT is not equivalent to VERIFIED.
    """

    answer: str = Field(
        min_length=1,
    )

    claims: list[
        MedOntoClaim
    ] = Field(
        default_factory=list,
    )

    considered_constraints: list[
        MedOntoConstraintReference
    ] = Field(
        default_factory=list,
    )

    status: Literal[
        "DRAFT",
        "ABSTAINED",
    ]


class PublicCitation(BaseModel):
    """
    Citation metadata safe to expose through the API.

    Metadata is reconstructed from actual retrieval results,
    not generated by the model.
    """

    chunk_id: str = Field(
        min_length=1,
    )

    document_id: str = Field(
        min_length=1,
    )

    title: str = Field(
        min_length=1,
    )

    section_title: str | None = None

    page_number: int | None = Field(
        default=None,
        ge=1,
    )

    source_url: str | None = None


class PublicOntologyConstraint(BaseModel):
    """
    Explicit ontology relationship safe to expose through
    the public API.
    """

    constraint_type: str = Field(
        min_length=1,
    )

    subject_name: str = Field(
        min_length=1,
    )

    predicate_name: str = Field(
        min_length=1,
    )

    object_name: str = Field(
        min_length=1,
    )


class RetrievalSummary(BaseModel):
    """
    High-level retrieval behavior safe for API consumers.
    """

    result_count: int = Field(
        ge=0,
    )

    used_ontology_filter: bool

    retrieval_relaxed: bool


class MedOntoQueryResponse(BaseModel):
    """
    Stable public response contract for POST /query.

    Internal LangGraph state, validator reasoning, prompts,
    retry details, and model messages are deliberately omitted.
    """

    query: str = Field(
        min_length=1,
    )

    answer: str = Field(
        min_length=1,
    )

    status: Literal[
        "VERIFIED",
        "ABSTAINED",
        "ERROR",
    ]

    citations: list[
        PublicCitation
    ] = Field(
        default_factory=list,
    )

    ontology_constraints: list[
        PublicOntologyConstraint
    ] = Field(
        default_factory=list,
    )

    retrieval: RetrievalSummary